"""Base Lightning module implementing data normalization and writing model summary to file."""

import os

import lightning.pytorch as pl
from lightning.pytorch.utilities.model_summary.model_summary import ModelSummary


class LightningModuleWithSummary(pl.LightningModule):
    """Base Lightning module that includes a method to summarize the model."""

    LOG_WEIGHTS_AND_GRADS = False

    def summarize(self) -> str:
        """Generate a formatted summary string for the model instance.

        The summary includes:
            - A header labeled 'Summary' followed by a textual summary generated by ModelSummary.
            - A header labeled 'Model' followed by the string representation of the model itself.

        Returns:
            str: The formatted summary string.
        """

        s = f"=== Summary {'=' * 31}\n"
        s += f"{ModelSummary(self)!s}\n\n"
        s += f"=== Model {'=' * 33}\n"
        s += f"{self!s}"

        return s

    def on_train_start(self) -> None:
        """Get called at the beginning of the training process.

        Ensures that the logger is properly set and its log directory exists.
        Creates the log directory if it does not exist.
        Writes a model summary to 'model_summary.txt' in the logger's log directory.

        Raises:
            AttributeError: If `self.logger` is not set.
            KeyError: If the logger does not have a `log_dir` attribute or it is None.

        Returns:
            None
        """

        if self.logger is None:
            raise AttributeError("self.logger is not set.")

        if not hasattr(self.logger, "log_dir") or (self.logger.log_dir is None):
            raise KeyError("logger has no attribute 'log_dir', or it is None.")

        os.makedirs(self.logger.log_dir, exist_ok=True)
        with open(os.path.join(self.logger.log_dir, "model_summary.txt"), "w") as f:
            f.write(self.summarize())

        return super().on_train_start()

    def on_after_backward(self):
        """Log model gradients."""

        if not self.LOG_WEIGHTS_AND_GRADS:
            return

        # Iterating through all parameters
        logger = self.logger
        if logger is None:
            raise ValueError("`logger` must be set to log parameters.")
        experiment = logger.experiment  # type: ignore

        for name, param in self.named_parameters():
            if param.requires_grad and param.grad is not None:
                experiment.add_histogram(name + ".grad", param.grad, self.global_step)

    def on_after_optimizer_step(self, *args, **kwargs):
        """Log model parameters after optimizer step."""

        if not self.LOG_WEIGHTS_AND_GRADS:
            return

        # Iterating through all parameters
        logger = self.logger
        if logger is None:
            raise ValueError("`logger` must be set to log parameters.")
        experiment = logger.experiment  # type: ignore

        for name, param in self.named_parameters():
            experiment.add_histogram(name + ".weight", param, self.global_step)
